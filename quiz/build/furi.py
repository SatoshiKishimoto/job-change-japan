KEYS = sorted(OVR, key=len, reverse=True)
KRE = re.compile("|".join(re.escape(k) for k in KEYS))

def kata2hira(s):
    return "".join(chr(ord(c)-0x60) if 'ァ'<=c<='ヶ' else c for c in s)

def ruby(base, rd):
    # 送り仮名・前置き仮名を分離
    if not KANJI.search(base): return html.escape(base)
    pre = post = ""
    b, r = base, rd
    while b and r and not KANJI.search(b[-1]) and kata2hira(b[-1]) == r[-1]:
        post = b[-1] + post; b = b[:-1]; r = r[:-1]
    while b and r and not KANJI.search(b[0]) and kata2hira(b[0]) == r[0]:
        pre += b[0]; b = b[1:]; r = r[1:]
    if not r or not b: return html.escape(base)
    return f"{html.escape(pre)}<ruby>{html.escape(b)}<rt>{r}</rt></ruby>{html.escape(post)}"

UNKNOWN = set()
def tag_plain(s):
    out = []
    for w in T(s):
        sf = w.surface
        if not KANJI.search(sf):
            out.append(html.escape(sf)); continue
        k = w.feature.kana
        if not k or k == "*":
            UNKNOWN.add(sf); out.append(html.escape(sf)); continue
        out.append(ruby(sf, kata2hira(k)))
    # fugashi drops whitespace; preserve by tagging chunks separately
    return "".join(out)

def furigana(text):
    res, pos = [], 0
    for m in KRE.finditer(text):
        if m.start() > pos: res.append(_chunk(text[pos:m.start()]))
        res.append(ruby(m.group(), OVR[m.group()]))
        pos = m.end()
    if pos < len(text): res.append(_chunk(text[pos:]))
    return "".join(res)

def _chunk(s):
    # 空白を保持
    parts = re.split(r'(\s+)', s)
    return "".join(html.escape(p) if p.isspace() or not p else tag_plain(p) for p in parts)

def readings(text):
    """確認用: 漢字語と読みの一覧"""
    pairs = []
    pos = 0
    for m in KRE.finditer(text):
        pos = m.end()
    for w in T(KRE.sub("　", text)):
        if KANJI.search(w.surface):
            pairs.append((w.surface, kata2hira(w.feature.kana or "?")))
    return pairs
